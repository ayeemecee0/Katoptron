'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const base=process.env.KATOPTRON_SMOKE_BASE||'http://127.0.0.1:8765/';
  const res=await page.goto(new URL('agency-xray.html',base).href,{waitUntil:'domcontentloaded',timeout:25000});
  assert.equal(res.status(),200);
  await page.waitForFunction(()=>document.querySelector('#originalStatus')?.textContent?.includes('6 source-identified agency dossiers'),
   null,{timeout:18000});
  assert.equal(await page.locator('#originalList button').count(),6);
  assert.match(await page.locator('#originalStatus').textContent(),/10 original-page-reviewed documents/);
  assert.match(await page.locator('#verifiedOriginals').textContent(),/not live camera verification/);
  await page.locator('#originalSearch').fill('Oklahoma City');
  assert.equal(await page.locator('#originalList button').count(),1);
  await page.locator('#originalList button').first().click();
  assert.equal(await page.locator('#originalDossier').getAttribute('hidden'),null);
  assert.match(await page.locator('#originalTitle').textContent(),/Oklahoma City · OK/);
  assert.equal(await page.locator('#originalDocuments article').count(),4);
  assert.match(await page.locator('#originalDocuments').textContent(),/executed 2026 federal-access amendment/);
  assert.match(await page.locator('#originalDocuments').textContent(),/not a final vote/);
  assert.match(await page.locator('#originalDocuments').textContent(),/not proof that \$270,000 was spent/);
  assert.match(await page.locator('#originalDocuments').textContent(),/109 partner organizations/);
  assert.match(page.url(),/original=oklahoma-city-ok/);
  const urls=await page.locator('#originalDocuments a').evaluateAll(as=>as.map(a=>a.href));
  assert.ok(urls.length>=7);
  assert.ok(urls.every(x=>x.startsWith('https://www.okc.gov/')&&/#page=\d+/.test(x)));
  await page.locator('#originalSearch').fill('Kittitas');
  assert.equal(await page.locator('#originalList button').count(),1);
  await page.locator('#originalList button').first().click();
  assert.equal(await page.locator('#originalDocuments article').count(),1);
  assert.match(await page.locator('#originalDocuments').textContent(),/DRAFT/);
  assert.match(await page.locator('#originalDocuments').textContent(),/does not verify/i);
  assert.match(await page.locator('#originalSummary').textContent(),/not live device timestamps/);
  await page.locator('#originalSearch').fill('Moline');
  await page.locator('#originalList button').first().click();
  assert.equal(await page.locator('#originalDocuments article').count(),2);
  assert.match(await page.locator('#originalDocuments').textContent(),/signed contract pause/i);
  assert.match(await page.locator('#originalDocuments').textContent(),/not proof of completed/i);
  await page.locator('#originalSearch').fill('Dakota County');
  await page.locator('#originalList button').first().click();
  assert.equal(await page.locator('#originalDocuments article').count(),1);
  assert.match(await page.locator('#originalDocuments').textContent(),/43 NCIC confirmed matches/);
  assert.match(await page.locator('#originalDocuments').textContent(),/not independently audited arrests/);
  await page.locator('#originalSearch').fill('Providence');
  await page.locator('#originalList button').first().click();
  assert.match(await page.locator('#originalDocuments').textContent(),/General Order 350.05/);
  await page.locator('#originalSearch').fill('Brookings');
  await page.locator('#originalList button').first().click();
  assert.match(await page.locator('#originalDocuments').textContent(),/Policy 13D1/);
  await page.locator('#originalClear').click();
  assert.equal(await page.locator('#originalList button').count(),6);
  assert.equal(await page.locator('#originalDossier').getAttribute('hidden'),'');
  assert.ok(!page.url().includes('original='));
  assert.equal(errors.length,0,errors.join('; '));
  await page.goto(new URL('agency-xray.html?original=moline-police-il',base).href,{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.querySelector('#originalTitle')?.textContent?.includes('Moline Police Department'),null,{timeout:18000});
  assert.equal(await page.locator('#originalDocuments article').count(),2);
  console.log('AGENCY X-RAY ORIGINAL DOSSIERS CHROMIUM PASS: 6 independently typed agency profiles, 10 sources, 28 page findings and source links');
 }finally{await browser.close();}
})().catch(e=>{console.error('AGENCY X-RAY ORIGINAL DOSSIERS FAILED',e);process.exit(1);});
