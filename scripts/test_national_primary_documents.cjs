'use strict';
const assert=require('node:assert/strict');
const App=require('../national-primary-documents.js');
const catalog=require('../data/verified-national-government-documents.json');
const rows=App.catalog(catalog);
assert.equal(rows.length,8);
assert.equal(new Set(rows.map(x=>x.source_url)).size,8);
assert.equal(catalog.source_review_held.length,1);
assert.equal(rows.filter(x=>x.kind==='draft_policy_unadopted').length,1);
assert.equal(rows.filter(x=>x.kind==='published_department_policy').length,1);
const policy=rows.find(x=>x.kind==='published_department_policy');
const draft=rows.find(x=>x.kind==='draft_policy_unadopted');
const commission=rows.find(x=>x.kind==='advisory_recommendation_not_binding_action');
const order=rows.find(x=>x.kind==='government_published_vendor_order_form');
const month=rows.find(x=>x.kind==='agency_monthly_aggregate_report');
assert.match(policy.findings[0].statement,/30-day/);
assert.match(draft.findings[0].statement,/seven days/);
assert.match(draft.findings[0].statement,/not a verified adopted policy/i);
assert.match(commission.findings[0].statement,/recommendation, not that Austin City Council ordered a halt/);
assert.match(order.findings[0].statement,/published Flock order form/);
assert.match(order.findings[1].statement,/not verification that every installment was paid/);
assert.match(month.findings[0].statement,/443,664 unique plate reads/);
assert.match(month.findings[1].statement,/not proof of each agency's current permissions/);
assert.ok(rows.every(x=>App.sourceLink(x)===x.source_url));
assert.ok(rows.every(x=>x.findings.every(f=>x.pages_reviewed.includes(f.page))));
assert.ok(rows.some(x=>x.source_date===null));
assert.equal(App.valid({...draft,status:'approved_and_implemented'}),false);
assert.equal(App.valid({...commission,kind:'city_council_action'}),false);
assert.equal(App.valid({...order,status:'fully_executed'}),false);
assert.equal(App.sourceLink({...draft,source_url:'https://www.greenbaywi.gov.evil.example/DocumentCenter/View/19136/x'}),null);
assert.throws(()=>App.catalog({...catalog,documents:[...rows.slice(0,7),rows[0]]}),/Unverified/);
assert.throws(()=>App.catalog({...catalog,source_review_held:[]}),/Unverified/);
console.log('NATIONAL PRIMARY DOCUMENTS PASS: eight pinned originals, draft vs adopted, nonbinding recommendation, contract execution unknown and aggregate access caveats');
