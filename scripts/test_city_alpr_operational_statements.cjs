'use strict';
const assert=require('node:assert/strict');
const API=require('../city-alpr-operational-statements.js');
const data=require('../data/verified-city-alpr-operational-statements.json');
const docs=API.catalog(data);
assert.equal(docs.length,2);
const moline=docs.find(r=>r.city==='Moline'),mill=docs.find(r=>r.city==='Mill Valley');
assert.equal(moline.effective_as_of,null);
assert.match(moline.classification,/future_deactivation_not_confirmed_completed/);
assert.match(moline.summary,/neither the announcement nor the signed pause agreement independently confirms/i);
assert.equal(mill.effective_as_of,'2026-09-09');
assert.equal(mill.statement_published_on,'2026-10-19');
assert.match(mill.classification,/city_reports_flock_cameras_already_disabled/);
assert.match(mill.evidence_limit,/not a third-party forensic audit/);
assert.ok(docs.every(d=>API.source(d)===d.source_url));
assert.ok(docs.every(d=>!('installation_count' in d)&&!('camera_coordinates' in d)));
assert.equal(API.valid({...moline,classification:mill.classification}),false);
assert.equal(API.valid({...moline,effective_as_of:'2026-09-29'}),false);
assert.equal(API.valid({...mill,classification:'confirmed_vendor_shutdown'}),false);
assert.equal(API.valid({...mill,source_url:'https://www.cityofmillvalley.gov.evil.example/'}),false);
assert.equal(API.valid({...mill,agency:'San Bruno Police Department'}),false);
assert.equal(API.valid({...mill,original_html_sha256_at_review:'0'.repeat(64)}),false);
assert.throws(()=>API.catalog({...data,documents:[mill,mill]}),/Unverified/);
console.log('CITY ORIGINAL OPERATIONAL STATUS PASS: separate Moline planned future event from retrospective Mill Valley city self-report');
