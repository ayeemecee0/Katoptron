'use strict';
const assert=require('node:assert/strict');
const H=require('../audit-history.js');
const report=require('../data/verified-independent-audits.json');
const wood=H.compare(report.reports,'woodbury|MN');
assert.equal(wood.length,2,'Woodbury has an earlier documented hardware-type change plus Flock count comparison');
const earlier=wood.find(x=>x.type==='historical_platform_difference');
const count=wood.find(x=>x.type==='reported_stationary_count_comparison');
assert.ok(earlier,'BOSS-backed mobile history must remain qualitative');
assert.match(earlier.detail,/Manufacturer unconfirmed \(BOSS software\)/);
assert.match(earlier.detail,/Flock Safety/);
assert.match(earlier.earlier_period_label,/months only/);
assert.ok(!Object.hasOwn(earlier,'reported_delta'),'Never subtract mobile and fixed reader counts');
assert.equal(count.previous_value,15);
assert.equal(count.current_value,17);
assert.equal(count.reported_delta,2);
assert.match(count.detail,/not verified additions/);
assert.ok(count.citations.every(x=>x.includes('#page=2')));
const sh=H.compare(report.reports,'shakopee|MN');
assert.equal(sh.length,1,'Shakopee only has a platform change, not a comparable count delta');
assert.equal(sh[0].type,'historical_platform_difference');
assert.match(sh[0].detail,/Elsag/);
assert.match(sh[0].detail,/Flock Safety/);
assert.ok(!Object.hasOwn(sh[0],'reported_delta'));
const edina=H.compare(report.reports,'edina|MN');
assert.equal(edina.length,1);
assert.equal(edina[0].type,'historical_platform_difference');
assert.match(edina[0].detail,/Manufacturer unconfirmed \(BOSS software\)/);
assert.match(edina[0].earlier_period_label,/audit snapshot/);
assert.ok(!Object.hasOwn(edina[0],'reported_delta'));
assert.deepEqual(H.compare(report.reports,'west saint paul|MN'),[]);
assert.deepEqual(H.compare(report.reports,'wyoming|MN'),[]);
assert.deepEqual(H.compare(report.reports,'stillwater|MN'),[]);
const a=report.reports.find(x=>x.id==='woodbury-mn-independent-flock-alpr-audit-2024');
const b=report.reports.find(x=>x.id==='woodbury-mn-independent-flock-alpr-audit-2026');
function noCountChange(old,newer,why){
 const events=H.compare([old,newer],'woodbury|MN');
 assert.equal(events.filter(x=>x.type==='reported_stationary_count_comparison').length,0,why);
}
noCountChange(a,{...b,jurisdiction_key:'different|MN'},'Do not merge by city name');
noCountChange(a,{...b,agency_name:'Woodbury Other Agency'},'Do not merge different agencies');
noCountChange(a,{...b,content_sha256:'0'.repeat(63)},'Unverified digest');
noCountChange(a,{...b,period_start:'2023-06-01'},'Overlapping periods');
noCountChange(a,{...b,cross_period:{...b.cross_period,agency_id:'other-agency-mn'}},'No fuzzy identity');
noCountChange(a,{...b,cross_period:{...b.cross_period,metrics:[{...b.cross_period.metrics[0],vendor:'Elsag'}]}},'Cross-vendor counts');
noCountChange(a,{...b,cross_period:{...b.cross_period,metrics:[{...b.cross_period.metrics[0],deployment:'patrol_vehicle'}]}},'Mixed deployment type');
noCountChange(a,{...b,cross_period:{...b.cross_period,metrics:[{...b.cross_period.metrics[0],page:7}]}},'Page not reviewed');
noCountChange(a,{...b,source_url:'https://evil.example/260248.pdf'},'Off-archive report');
noCountChange(a,{...b,report_date:'2026-02-30'},'Invalid date');
noCountChange(a,{...b,period_precision:'audit_snapshot_only',period_label:''},'Empty unsupported scope label');
assert.equal(H.originalUrl('https://www.lrl.mn.gov.evil.example/docs/2024/mandated/240350.pdf'),null);
assert.equal(H.originalUrl('https://www.lrl.mn.gov/docs/2024/mandated/240350.pdf#page=2'),null);
